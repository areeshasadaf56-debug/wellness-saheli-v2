    RegExp(r'^(\d+) of (\d+) methods rated "safe to use"$'),
    (m) => '${m[2]} میں سے ${m[1]} طریقے "استعمال کے لیے محفوظ" قرار پائے',
  ),
  (RegExp(r'^Model used: (.+)$'), (m) => 'استعمال شدہ ماڈل: ${m[1]}'),
];

/// Returns the Urdu version of [s], or [s] unchanged if there is none yet.
String translate(String s) {
  final hit = _ur[s];
  if (hit != null) return hit;

  final t = s.trim();
  if (t.isEmpty) return s;
  if (t != s) {
    final h2 = _ur[t];
    if (h2 != null) {
      final start = s.indexOf(t);
      return '${s.substring(0, start)}$h2${s.substring(start + t.length)}';
    }
  }

  for (final (re, build) in _patterns) {
    final m = re.firstMatch(t);
    if (m != null) return build(m);
  }
  return s;
}
